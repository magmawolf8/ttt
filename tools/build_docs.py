"""Build/check a portable static documentation site, without simulation imports."""
import argparse
from collections import Counter
import hashlib
from html import escape
from html.parser import HTMLParser
import json
import os
from pathlib import Path
import re
from urllib.parse import unquote, urlsplit, urlunsplit

from markdown_it import MarkdownIt

ROOT=Path(__file__).resolve().parents[1]
DOCS=ROOT/"docs"
MARKER="<!-- Generated by tools/build_docs.py; edit the Markdown source. -->"


def relative(target, origin):
    return Path(os.path.relpath(target, origin.parent)).as_posix()


def source_path(name):
    path=(DOCS/name).resolve()
    if not path.is_relative_to(DOCS.resolve()) or path.suffix!=".md" or not path.is_file():
        raise ValueError(f"Invalid Markdown source: {name}")
    return path


def navigation(config, current):
    groups=[]
    for group in config["groups"]:
        links=[]
        for page in group["pages"]:
            target=source_path(page["source"]).with_suffix(".html")
            selected=' aria-current="page"' if target==current else ""
            links.append(f'<li><a href="{escape(relative(target,current))}"{selected}>{escape(page["label"])}</a></li>')
        groups.append(f'<section class="nav-group"><h2>{escape(group["title"])}</h2><ul>{"".join(links)}</ul></section>')
    return '<nav aria-label="Documentation">'+"".join(groups)+"</nav>"


def markdown(source, outputs):
    md=MarkdownIt("commonmark",{"html":True}).enable("table")
    md.renderer.rules["table_open"]=lambda *args: '<div class="table-scroll" tabindex="0" role="region" aria-label="Data table"><table>\n'
    md.renderer.rules["table_close"]=lambda *args: '</table></div>\n'
    tokens=md.parse(source.read_text(encoding="utf-8"))
    headings=[]
    used=Counter()
    title=None
    for i,token in enumerate(tokens):
        if token.type=="heading_open":
            text="".join(child.content for child in tokens[i+1].children or [] if child.type in {"text","code_inline"})
            slug=re.sub(r"\s+","-",re.sub(r"[^\w\s-]","",text.lower()).strip()) or "section"
            used[slug]+=1
            anchor=slug if used[slug]==1 else f"{slug}-{used[slug]}"
            token.attrSet("id",anchor)
            if token.tag=="h1":
                if title is not None:
                    raise ValueError(f"More than one page title in {source}")
                title=text
            elif token.tag=="h2":
                headings.append((anchor,text))
        for child in token.children or []:
            if child.type!="link_open":
                continue
            url=urlsplit(child.attrGet("href") or "")
            if url.scheme or url.netloc or not url.path:
                continue
            destination=(source.parent/unquote(url.path)).resolve()
            if destination in outputs:
                child.attrSet("href",urlunsplit(("","",relative(outputs[destination],source),url.query,url.fragment)))
    if title is None:
        raise ValueError(f"Missing page title in {source}")
    return title,headings,md.renderer.render(tokens,md.options,{})


def page_html(config, page, group, outputs):
    source=source_path(page["source"])
    target=outputs[source]
    title,headings,body=markdown(source,outputs)
    nav=navigation(config,target)
    home=escape(relative(DOCS/"index.html",target))
    style=escape(relative(DOCS/"static/site.css",target))
    source_url=escape(relative(source,target))
    evidence=escape(relative(DOCS/"evidence/index.html",target))
    toc=""
    if headings:
        links="".join(f'<li><a href="#{escape(anchor)}">{escape(text)}</a></li>' for anchor,text in headings)
        toc=f'<details class="toc"><summary>On this page</summary><ul>{links}</ul></details>'
    brand=escape(config["title"])
    return f'''<!doctype html>
{MARKER}
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="description" content="{escape(page["description"])}">
  <meta name="theme-color" content="#124b67">
  <title>{escape(title)} · {brand}</title>
  <link rel="stylesheet" href="{style}">
</head>
<body>
  <a class="skip" href="#content">Skip to content</a>
  <aside class="sidebar">
    <a class="brand" href="{home}"><span class="brand-mark" aria-hidden="true">UR</span>{brand}</a>
    <p class="subtitle">{escape(config["subtitle"])}</p>
    {nav}
    <p class="nav-note">Development prototype<br>Frozen policy · experimental adapter</p>
  </aside>
  <header class="mobile-header">
    <a class="brand" href="{home}">{brand}</a>
    <details><summary>Browse documentation</summary>{nav}</details>
  </header>
  <main id="content" tabindex="-1">
    <div class="article-shell">
      <p class="eyebrow">{escape(group)}</p>
      {toc}
      <article>{body}</article>
      <footer>
        <div class="footer-links"><a href="{source_url}">Markdown source</a><a href="{evidence}">Evidence &amp; provenance</a><a href="{home}">Project overview</a></div>
        <p>Development documentation. Historical experiments are labelled separately from the current runtime.</p>
      </footer>
    </div>
  </main>
</body>
</html>
'''


class References(HTMLParser):
    def __init__(self,text):
        super().__init__(convert_charrefs=True)
        self.ids=[]
        self.urls=[]
        self.feed(text)

    def handle_starttag(self,tag,attrs):
        for key,value in attrs:
            if key=="id" and value:
                self.ids.append(value)
            if key in {"href","src","poster"} and value:
                self.urls.append(value)


def validate(rendered):
    parsed={path:References(content) for path,content in rendered.items()}
    errors=[]
    for path,document in parsed.items():
        for anchor,count in Counter(document.ids).items():
            if count>1:
                errors.append(f"{path.relative_to(DOCS)}: duplicate id {anchor}")
        for value in document.urls:
            url=urlsplit(value)
            if url.scheme or url.netloc:
                continue
            if url.path.startswith("/"):
                errors.append(f"{path.relative_to(DOCS)}: root-absolute URL breaks project hosting: {value}")
                continue
            destination=(path.parent/unquote(url.path)).resolve() if url.path else path
            if not destination.is_relative_to(DOCS.resolve()):
                errors.append(f"{path.relative_to(DOCS)}: link leaves published docs: {value}")
            elif destination not in rendered and not destination.is_file():
                errors.append(f"{path.relative_to(DOCS)}: missing link target {value}")
            elif url.fragment and destination in parsed and unquote(url.fragment) not in parsed[destination].ids:
                errors.append(f"{path.relative_to(DOCS)}: missing anchor {value}")
    manifest=json.loads((DOCS/"evidence/manifest.json").read_text(encoding="utf-8"))
    for entry in manifest["files"]:
        path=(DOCS/entry["file"]).resolve()
        if not path.is_relative_to(DOCS.resolve()) or not path.is_file():
            errors.append(f"Missing evidence: {entry['file']}")
            continue
        content=path.read_bytes()
        if len(content)!=entry["bytes"] or hashlib.sha256(content).hexdigest()!=entry["sha256"]:
            errors.append(f"Evidence bytes changed: {entry['file']}")
    if not (DOCS/".nojekyll").is_file():
        errors.append("Missing docs/.nojekyll for direct branch publishing")
    if errors:
        raise ValueError("\n".join(errors))
    return sum(len(document.urls) for document in parsed.values()),len(manifest["files"])


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check",action="store_true",help="Verify generated pages, links and evidence without writing")
    args=parser.parse_args()
    config=json.loads((DOCS/"site.json").read_text(encoding="utf-8"))
    pages=[(page,group["title"]) for group in config["groups"] for page in group["pages"]]
    outputs={source_path(page["source"]):source_path(page["source"]).with_suffix(".html") for page,_ in pages}
    if len(outputs)!=len(pages):
        raise ValueError("Duplicate page in site.json")
    unlisted=set(DOCS.rglob("*.md"))-set(outputs)-{DOCS/"README.md"}
    if unlisted:
        raise ValueError(f"Markdown pages missing from site.json: {sorted(str(p) for p in unlisted)}")
    rendered={outputs[source_path(page["source"])]:page_html(config,page,group,outputs) for page,group in pages}
    extra=set(DOCS.rglob("*.html"))-set(rendered)
    if extra:
        raise ValueError(f"Unexpected HTML pages; review/remove obsolete generated files: {sorted(str(p) for p in extra)}")
    links,evidence=validate(rendered)
    stale=[]
    for path,content in rendered.items():
        expected=content.encode("utf-8")
        if args.check:
            if not path.exists() or path.read_bytes()!=expected:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True,exist_ok=True)
            path.write_bytes(expected)
    if stale:
        raise ValueError("Stale HTML; run python tools/build_docs.py:\n"+"\n".join(stale))
    print(f"{'Checked' if args.check else 'Built'} {len(rendered)} pages; {links} references and {evidence} evidence/media hashes verified.")


if __name__=="__main__":
    try:
        main()
    except (ValueError,FileNotFoundError) as error:
        raise SystemExit(str(error)) from error
